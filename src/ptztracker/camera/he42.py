"""Замеры живой Panasonic AW-HE42 (диагностика 2026-10-19 и площадка 2026-10-29, §7 спеки) — единый источник
для модели регулятора (control.camera_model) и симулятора (sim.ptz_model). Меняются только по новым замерам.

Единицы: pan/tilt — градусы в секунду по коду 51–99 (50 — стоп, < 50 — зеркально); в доли кадра их переводит
угол обзора на текущем зуме (hfov_deg); зум — ln(масштаба) в секунду по коду #Z.
"""

import math

# Скорость pan и tilt, °/с. Камера держит её постоянной при любом зуме («Speed With Zoom Pos.» выключена:
# код 53 ≈ 0,17°/с и на 555, и на AAA, и на FFF), наклон — ровно как поворот. Источник — мастер калибровки
# на площадке 2026-10-29 (19:25, зум 0x555, шкала #APC 0,0083; повтор совпал в пределах 1,5%). Прямой замер
# по #APC (55 0,31 · 58 0,80 · 60 1,70 · 63 3,65 · 65 6,05 · 70 13,0 · 75 21,5) ниже на 3–7%: запас в сторону
# «камера медленнее модели», он безопасен. Выше 90 мастер не мерил: 99 продлено по форме кривой (прирост
# 1,7 → 2,2 → 2,8°/с на код у 70–75–80–90, дальше ~3,3) — около 90°/с; не мерялось.
PAN_DEG_S: dict[int, float] = {
    53: 0.18, 55: 0.32, 57: 0.59, 59: 1.26, 61: 2.37, 63: 3.83, 65: 6.33, 67: 9.4,
    70: 13.62, 75: 22.24, 80: 32.99, 90: 60.99, 99: 90.0,
}

# AW-HE40 (клуб, 2026-10-30, мастер и прямой замер по #APC): на 555 и AAA те же °/с в пределах 0–3% на кодах 53–67,
# на 70–90 быстрее на 2–17% (запас «камера быстрее модели» — его ловит подстройка скорости, таблицу не меняем).
# На теле поворот замедляется (замер HE40; провал быстрых кодов на FFF у HE42 2026-10-29 — похоже, то же самое):
# до 0xD54 как PAN_DEG_S, дальше °/с по коду. Модель регулятора (control.camera_model) и симулятор (sim.ptz_model)
# берут °/с через pan_deg_s / tele_pan_ratio ниже.
TELE_PAN_DEG_S: dict[int, dict[int, float]] = {
    0xEA9: {55: 0.32, 63: 2.27, 75: 9.92},
    0xFFF: {55: 0.32, 59: 0.69, 63: 1.20, 70: 2.47, 75: 5.10},
}
TELE_START_GZ = 0xD54  # выше этого положения #GZ поворот замедляется

# AW-HE40 на кодах 70–90 быстрее таблицы PAN_DEG_S на 2–17% (клуб, 2026-10-30). Только справка для профиля модели
# (camera.models): таблица одна, расхождение ловит подстройка скорости (control.speed_adapt).
HE40_FASTER_CODES = (70, 90)
HE40_FASTER_PCT = (2, 17)


def pan_base_deg_s(code: int) -> float:
    """Скорость pan/tilt на зуме до 0xD54, °/с (по модулю): линейно между точками PAN_DEG_S, код 50 — 0,
    выше последней точки — она же."""
    n = 50 + abs(code - 50)
    pts = [(50, 0.0), *sorted(PAN_DEG_S.items())]
    if n >= pts[-1][0]:
        return pts[-1][1]
    for (c0, v0), (c1, v1) in zip(pts, pts[1:]):
        if c0 <= n <= c1:
            return v0 + (v1 - v0) * (n - c0) / (c1 - c0)
    return 0.0


def _tele_log_ratio(n: int, table: dict[int, float]) -> float:
    """ln(°/с на теле ÷ °/с до 0xD54) для кода n по одной таблице TELE_PAN_DEG_S: линейно по коду между
    замеренными кодами, за крайними — значение крайнего (ниже самого медленного замера замедления нет в замере,
    выше самого быстрого — доля замедления держится; выше 75 живьём не мерялось)."""
    pts = sorted((c, math.log(v / pan_base_deg_s(c))) for c, v in table.items())
    if n <= pts[0][0]:
        return pts[0][1]
    if n >= pts[-1][0]:
        return pts[-1][1]
    for (c0, r0), (c1, r1) in zip(pts, pts[1:]):
        if c0 <= n <= c1:
            return r0 + (r1 - r0) * (n - c0) / (c1 - c0)
    return 0.0


def tele_pan_ratio(code: int, gz: int) -> float:
    """Во сколько раз поворот на теле медленнее, чем до 0xD54 (1 — не замедлен), для кода 01–99 и положения #GZ.
    Между 0xD54 (доля 1) и замеренными зумами — линейно по логарифму °/с; выше последнего замера — его значение."""
    if gz <= TELE_START_GZ:
        return 1.0
    n = 50 + abs(code - 50)
    knots = [(TELE_START_GZ, 0.0)] + [(z, _tele_log_ratio(n, t)) for z, t in sorted(TELE_PAN_DEG_S.items())]
    if gz >= knots[-1][0]:
        return math.exp(knots[-1][1])
    for (z0, r0), (z1, r1) in zip(knots, knots[1:]):
        if z0 <= gz <= z1:
            return math.exp(r0 + (r1 - r0) * (gz - z0) / (z1 - z0))
    return 1.0


def pan_deg_s(code: int, gz: int) -> float:
    """Скорость pan/tilt, °/с (по модулю) для кода 01–99 при положении зума #GZ: PAN_DEG_S, на теле — замедленная."""
    return pan_base_deg_s(code) * tele_pan_ratio(code, gz)


# Зум: #Z75 × 0.7 с → картинка ×1.21; остальные точки — по форме кривой.
ZOOM_LN_S: dict[int, float] = {55: 0.02, 60: 0.05, 65: 0.1, 75: 0.27, 85: 0.5, 99: 0.8}

# Оптический зум 20× (паспорт). Положение #GZ 0x555–0xFFF считаем линейным по ln(масштаба) — так
# устроен симулятор; живьём соответствие не мерялось. Регулятор по нему подправляет свою модель зума.
ZOOM_RATIO = 20.0

# Разгон/торможение: 2026-10-29 по кадрам MJPEG до 90% за 0,27–0,33 с, мастер нашёл τ 0,10 с (дважды) → τ 0,12 с
# (до 90% = 2,3·τ ≈ 0,28 с). 0,85 с и τ 0,37 с от 2026-10-19 — артефакт замера по H.264. Плюс мёртвое время.
RAMP_TAU_S = 0.12
DEAD_TIME_S = 0.08
# AW-HE40 отвечает быстрее (клуб, 2026-11-10, прямой замер по #APC): слушается через 0,05–0,07 с, после «стоп»
# проходит v·0,03–0,07 с и стоит через 0,05–0,11 с. Регулятор всё равно не берёт τ меньше 0,05 (framing._Axis._ramp).
HE40_DEAD_TIME_S = 0.05
HE40_RAMP_TAU_S = 0.05

# Задержка видео (кадр приходит позже съёмки), по типу потока. «Команда → движение в кадре»
# с разгоном: MJPEG 344 мс, H.264 ~830 мс.
# «mjpeg_2» (1280×720, 12 к/с с &framerate) — замер 2026-10-29: «команда → движение» 480 мс против 336 мс
# у MJPEG (1), то есть «mjpeg» + 0,14 с.
# 2026-11-10 (HE40, клуб, Wi‑Fi): «команда → кадр получен» MJPEG (1) 0,18–0,23 с, MJPEG (2) 0,28–0,36 с при отклике
# камеры 0,05–0,07 с — само видео опаздывает на ≈ 0,15 и ≈ 0,25 с (было 0,12 и 0,26). H.264 ≈ 0,39 с — замер шумный,
# оставлено 0,6 до замера по кабелю. Период кадров сюда не входит: его регулятор считает сам (control.timing).
VIDEO_LATENCY_S: dict[str, float] = {"mjpeg": 0.15, "mjpeg_2": 0.25, "h264": 0.6, "sim": 0.15}

# Оптика (паспорт AW-HE42, объектив 20×): горизонтальный угол обзора 62,1° на широком угле
# и 3,3° на теле. Площадка 2026-10-29 (§3б): до 0xD55 верно с точностью ~10%, на теле живьём 2,4°.
# По углу обзора °/с камеры переводятся в доли кадра: таблица регулятора без калибровки
# (control.camera_model.default_calibration), симулятор (картинка) и мастер калибровки (по #APC).
HFOV_WIDE_DEG, HFOV_TELE_DEG = 62.1, 3.3
# Предел поворота (паспорт AW-HE42): ±175° от середины #APC. Только для показа в «Положении камер».
PAN_LIMIT_DEG = 175.0


def hfov_deg(zoom_frac: float) -> float:
    """Горизонтальный угол обзора по доле диапазона зума (0 — широкий угол, 1 — теле; #GZ 0x555–0xFFF
    линейно). Угол меняется геометрически между паспортными концами — так устроен симулятор."""
    return HFOV_WIDE_DEG * (HFOV_TELE_DEG / HFOV_WIDE_DEG) ** zoom_frac

# Бочкообразная дисторсия: x_d = x·(1 + k1·r²), r — в долях фокусного расстояния. Оценка для
# широкоугольного зум-объектива (не замер): −0,08 на широком угле, к теле убывает до 0.
LENS_K1_WIDE = -0.08

# Шкала положения #APC: градусов на единицу. Замер 2026-10-29 (шаги ±256/±512 ед. на широком угле, сдвиг
# картинки при паспортном угле 62,1°): 0,0082–0,0086 по pan и tilt; у Panasonic 350° / 0xA5EF ≈ 0,00824.
# По ней сторож раскачки решает, сдвинулась ли камера (control.framing.WATCHDOG_APC_MIN_STEP), а мастер
# калибровки переводит положение в градусы/с.
APC_DEG_PER_UNIT = 0.0083
APC_CENTER = 0x8000  # #APC pan/tilt = 0° (середина диапазона)
